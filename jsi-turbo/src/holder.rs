//! Module instances and type-erased method tables.

use std::sync::Arc;

use jsi::{JsiValue, RuntimeHandle};

use crate::dispatcher::Dispatcher;

/// A type-erased module instance together with its method table. Stored as a
/// JS object's native state; the JS GC dropping the object drops the module.
pub struct ModuleHolder {
    inner: Arc<dyn std::any::Any + Send + Sync>,
    table: &'static MethodTable,
    /// Type-erased `T::turbo_external_size`, captured at construction so the
    /// proxy can report the size to the JS GC without knowing `T`.
    external_size: fn(&Arc<dyn std::any::Any + Send + Sync>) -> usize,
}

impl ModuleHolder {
    /// Constructs a module instance via its generated constructor.
    pub fn new<T: TurboModuleObject>() -> anyhow::Result<Self> {
        Ok(Self {
            inner: Arc::new(T::__turbo_construct()?),
            table: T::__turbo_method_table(),
            external_size: |inner: &Arc<dyn std::any::Any + Send + Sync>| {
                inner
                    .clone()
                    .downcast::<T>()
                    .map(|t| t.turbo_external_size())
                    .unwrap_or(0)
            },
        })
    }

    /// Wraps an already-constructed instance (nested `#[TurboObject]`
    /// values created by module methods, as opposed to registry-constructed
    /// module singletons).
    pub fn with_instance<T: TurboModuleObject>(value: T) -> Self {
        Self {
            inner: Arc::new(value),
            table: T::__turbo_method_table(),
            external_size: |inner: &Arc<dyn std::any::Any + Send + Sync>| {
                inner
                    .clone()
                    .downcast::<T>()
                    .map(|t| t.turbo_external_size())
                    .unwrap_or(0)
            },
        }
    }

    /// The module's [`TurboModuleObject::turbo_external_size`], for the JS
    /// GC's external memory accounting.
    pub fn external_size(&self) -> usize {
        (self.external_size)(&self.inner)
    }

    pub fn table(&self) -> &'static MethodTable {
        self.table
    }

    /// The concrete module instance, if this holder carries a `T`.
    pub fn downcast<T: std::any::Any + Send + Sync>(&self) -> Option<Arc<T>> {
        self.inner.clone().downcast::<T>().ok()
    }
}

// ModuleHolder is a concrete 'static type, so it implements Any + Send + Sync
// automatically and can be stored inside RustNativeCarrier's
// Box<dyn Any + Send + Sync>.

pub enum MethodKind {
    Method,
    Getter,
    Setter,
}

/// Type-erased method invoker generated by `#[RustTurboModule]`. Converts
/// arguments, calls the typed method and converts the result. The dispatcher
/// is only used by async methods (to hop resolve/reject back to the JS
/// thread); sync methods ignore it.
pub type InvokeFn = for<'rt> fn(
    &ModuleHolder,
    &Dispatcher,
    &mut RuntimeHandle<'rt>,
    &[JsiValue<'rt>],
) -> anyhow::Result<JsiValue<'rt>>;

pub struct MethodEntry {
    /// The name JavaScript sees (camelCase).
    pub js_name: &'static str,
    pub kind: MethodKind,
    pub param_count: usize,
    pub invoke: InvokeFn,
}

pub struct MethodTable {
    /// The module name used for registration and JS access.
    pub module_name: &'static str,
    /// The Rust type name, for diagnostics.
    pub rust_type: &'static str,
    pub entries: &'static [MethodEntry],
}

/// Implemented by every `#[RustTurboModule]` type; all items are generated
/// by the macro.
pub trait TurboModuleObject: Send + Sync + 'static {
    /// Constructs the module (default construction or a custom constructor).
    fn __turbo_construct() -> anyhow::Result<Self>
    where
        Self: Sized;
    /// This type's method table.
    fn __turbo_method_table() -> &'static MethodTable
    where
        Self: Sized;

    /// Bytes of native memory this instance keeps alive that the JS GC
    /// cannot see (e.g. large buffers). Reported via
    /// `jsi::Object::setExternalMemoryPressure` when the instance is handed
    /// to JS, so Hermes collects the wrapper more eagerly. Override by
    /// defining an inherent method with the same name next to the module's
    /// other methods.
    fn turbo_external_size(&self) -> usize {
        0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Sized(usize);

    impl TurboModuleObject for Sized {
        fn __turbo_construct() -> anyhow::Result<Self> {
            Ok(Sized(4096))
        }
        fn __turbo_method_table() -> &'static MethodTable {
            static TABLE: MethodTable = MethodTable {
                module_name: "Sized",
                rust_type: "Sized",
                entries: &[],
            };
            &TABLE
        }
        fn turbo_external_size(&self) -> usize {
            self.0
        }
    }

    struct Unsized;

    impl TurboModuleObject for Unsized {
        fn __turbo_construct() -> anyhow::Result<Self> {
            Ok(Unsized)
        }
        fn __turbo_method_table() -> &'static MethodTable {
            static TABLE: MethodTable = MethodTable {
                module_name: "Unsized",
                rust_type: "Unsized",
                entries: &[],
            };
            &TABLE
        }
    }

    #[test]
    fn external_size_is_captured_per_type() {
        assert_eq!(4096, ModuleHolder::new::<Sized>().unwrap().external_size());
        // the default trait implementation reports zero
        assert_eq!(0, ModuleHolder::new::<Unsized>().unwrap().external_size());
    }
}
