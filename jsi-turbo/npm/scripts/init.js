#!/usr/bin/env node
/**
 * `init <package-name>` — scaffold a rust-turbo module package.
 *
 * The three names are derived from ONE argument so they cannot drift
 * apart (drift = the classic silent-failure modes documented in the
 * usage guide):
 *   npm package name / cargo package name: my-math-utils   (as given)
 *   module name (#[RustTurboModule("..")]):  MyMathUtils    (PascalCase)
 */

const fs = require('fs');
const path = require('path');

function pascal(kebab) {
  return kebab
    .split('-')
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function usage() {
  console.error('usage: npx react-native-rust-turbo init <package-name>');
  console.error('  package-name: kebab-case, e.g. my-math-utils');
  process.exit(2);
}

function init(argv) {
  const name = argv[0];
  if (!name || argv.length !== 1 || !/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(name)) {
    usage();
  }
  const moduleName = pascal(name);
  const dir = path.resolve(name);

  if (fs.existsSync(dir)) {
    console.error(`init: ${dir} already exists`);
    process.exit(1);
  }

  fs.mkdirSync(path.join(dir, 'src'), {recursive: true});

  fs.writeFileSync(
    path.join(dir, 'package.json'),
    JSON.stringify(
      {
        name,
        version: '0.1.0',
        description: `Rust TurboModule(s) for React Native: ${moduleName}.`,
        license: 'MIT',
        main: `generated/rust-turbo/${moduleName}.ts`,
        files: ['src/', 'generated/', 'Cargo.toml'],
        'rust-turbo': {
          crate: '.',
          crateName: name,
          modules: [moduleName],
        },
      },
      null,
      2
    ) + '\n'
  );

  fs.writeFileSync(
    path.join(dir, 'Cargo.toml'),
    `# GENERATED by react-native-rust-turbo init — edit freely.
[package]
name = "${name}"
version = "0.1.0"
edition = "2021"
license = "MIT"

[lib]
# consumed by the app's aggregate library (built by react-native-rust-turbo)
crate-type = ["lib"]

[dependencies]
# the framework crates come from the core package's rust/ dir (a sibling
# in node_modules) — one copy in the cargo graph
jsi = { path = "../react-native-rust-turbo/rust/jsi", default-features = false, features = ["macros", "serde"] }
jsi-turbo = { path = "../react-native-rust-turbo/rust/jsi-turbo" }
linkme = "0.3"
anyhow = "1.0"
serde = { version = "1.0", features = ["derive"] }
`
  );

  fs.writeFileSync(
    path.join(dir, 'src', 'lib.rs'),
    `//! ${moduleName} — a Rust TurboModule for React Native.
//!
//! This impl block IS the spec: the method table, auto-registration and
//! the TypeScript bindings (\`generated/rust-turbo/${moduleName}.ts\`) are
//! all generated from it. Replace the demo methods with your own; see
//! the usage guide for the full type rules (async, structs, zero-copy
//! buffers, nested objects, JS callbacks).
//!
//! JS usage:
//!   import { get${moduleName} } from '${name}/generated/rust-turbo/${moduleName}';
//!   get${moduleName}().add(19, 23); // 42

use jsi::RuntimeHandle;
use jsi_turbo::RustTurboModule;

#[derive(Default)]
pub struct ${moduleName};

#[RustTurboModule("${moduleName}")]
impl ${moduleName} {
    pub fn add(&self, _rt: &mut RuntimeHandle, a: f64, b: f64) -> anyhow::Result<f64> {
        Ok(a + b)
    }

    pub fn greet(&self, name: String) -> anyhow::Result<String> {
        Ok(format!("Hello, {name}, from ${moduleName}!"))
    }

    /// Async methods run on a worker pool; JS gets a Promise.
    pub async fn slow_add(&self, a: f64, b: f64) -> anyhow::Result<f64> {
        Ok(a + b)
    }

    #[turbo(getter)]
    pub fn get_version(&self) -> anyhow::Result<String> {
        Ok(env!("CARGO_PKG_VERSION").into())
    }
}
`
  );

  fs.writeFileSync(
    path.join(dir, '.gitignore'),
    `# macro-generated TypeScript (rebuilt from the Rust sources)\n/generated/\n`
  );

  console.log(`created ${name}/
  package.json     (rust-turbo metadata: module ${moduleName})
  Cargo.toml       (framework deps via the core package)
  src/lib.rs       (a runnable demo module — make it yours)
  .gitignore

next steps:
  cd <your-app>
  npm install <path-to>/${name}
  # then from JS:
  import { get${moduleName} } from '${name}/generated/rust-turbo/${moduleName}';

adding more modules later: write another #[RustTurboModule("..")] impl
block in src/lib.rs AND append the module name to rust-turbo.modules
in package.json — a module missing from that list works on Android but
silently disappears on iOS.
`);
}

module.exports = init;
